import { iconSvg } from "../uiIcons.mjs";

export const participantOfflineLabel = "שם ללא חשבון";

function ownsAliasForm(dialog, eventId) {
  return dialog?.kind === "participant-identities" && dialog.eventId === eventId;
}

export function participantAliasDraftUpdate(dialog, eventId, participantId, value) {
  if (!ownsAliasForm(dialog, eventId) || !participantId) return null;
  return { ...dialog.aliasDrafts, [participantId]: String(value ?? "") };
}

export function participantAliasDraftValue(dialog, eventId, participantId, savedValue = "") {
  return ownsAliasForm(dialog, eventId) && Object.hasOwn(dialog.aliasDrafts ?? {}, participantId)
    ? String(dialog.aliasDrafts[participantId] ?? "") : savedValue;
}

export function participantAliasAcknowledgedDrafts(dialog, submittedDialog, eventId, participantId, submittedValue, ownsWrite) {
  if (!ownsWrite || dialog !== submittedDialog || !ownsAliasForm(dialog, eventId) ||
      !Object.hasOwn(dialog.aliasDrafts ?? {}, participantId) || dialog.aliasDrafts[participantId] !== submittedValue) return null;
  const drafts = { ...dialog.aliasDrafts };
  delete drafts[participantId];
  return drafts;
}

function escapeText(value = "") {
  return String(value ?? "").replace(/[&<>"']/g, character => ({
    "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#039;"
  })[character]);
}

// HTML slots are generated by the existing avatar, username and identity renderers.
function renderIdentityPerson({ name = "", avatarHtml = "", usernameHtml = "", connectionHtml = "" } = {}) {
  return `<div class="participant-identity-person">
    ${avatarHtml}<div class="participant-identity-person-copy">
      <strong>${escapeText(name)}</strong>${usernameHtml}${connectionHtml}
    </div>
  </div>`;
}

export function renderParticipantIdentityReviewView({
  message = "", pairsHtml = "", hasUnresolvedPairs = false,
  canManage = false, aliasEditorsHtml = ""
} = {}) {
  return `<section class="participant-identity-review" aria-label="בדיקת שמות דומים">
    ${message ? `<p class="participant-identity-result" role="status">${escapeText(message)}</p>` : ""}
    ${hasUnresolvedPairs ? `<div class="participant-identity-pairs">${pairsHtml}</div>`
      : !message ? '<p class="participant-identity-result" role="status">אין שמות שדורשים בדיקה.</p>' : ""}
    ${canManage && aliasEditorsHtml ? `<details class="participant-aliases">
      <summary><span>הוספת כינוי באירוע</span><span class="identity-disclosure-icon" aria-hidden="true">${iconSvg("chevron-left")}</span></summary>
      <p class="participant-alias-explanation">כינוי קצר עוזר להבחין ביניהם, ויופיע רק באירוע הזה.</p>
      <div class="participant-alias-list">${aliasEditorsHtml}</div>
    </details>` : ""}
    ${!hasUnresolvedPairs ? '<button type="button" class="secondary-button identity-review-return" data-action="participant-identities-back">חזרה למשתתפים</button>' : ""}
  </section>`;
}

export function renderParticipantIdentityPairView({
  eventId = "", pairKey = "", sourceId = "", targetId = "",
  canConnect = false, canManage = false, people = []
} = {}) {
  return `<article class="participant-identity-pair">
    <div class="participant-identity-question">
      <h3>${canConnect ? "זה אותו אדם?" : "שני חשבונות באותו שם"}</h3>
      <p>${canConnect ? "אם זה אותו אדם, אפשר לאחד את הרישומים באירוע." : "אלה חשבונות נפרדים, ולכן אי אפשר לקשר ביניהם."}</p>
    </div>
    <div class="participant-identity-people">${people.map(renderIdentityPerson).join("")}</div>
    ${canManage ? `<div class="participant-identity-actions">
      ${canConnect ? `<button class="primary-button" type="button" data-action="connect-duplicate-participant" data-event-id="${escapeText(eventId)}" data-source-participant-id="${escapeText(sourceId)}" data-target-participant-id="${escapeText(targetId)}">כן, אותו אדם</button>` : ""}
      <button class="${canConnect ? "secondary-button" : "primary-button"}" type="button" data-action="keep-duplicate-participants" data-event-id="${escapeText(eventId)}" data-participant-pair="${escapeText(pairKey)}">${canConnect ? "לא, אנשים שונים" : "אלה אנשים שונים"}</button>
      <button class="participant-identity-defer" type="button" data-action="defer-duplicate-participant" data-event-id="${escapeText(eventId)}">אבדוק אחר כך</button>
    </div>` : '<p class="participant-identity-manager-note">מנהל האירוע יכול לבדוק את השמות.</p>'}
  </article>`;
}

export function renderParticipantAliasEditorView({
  eventId = "", participantId = "", name = "", alias = "",
  avatarHtml = "", usernameHtml = "", connectionHtml = ""
} = {}) {
  const inputId = `identity-alias-${participantId}`;
  return `<div class="participant-alias-row">
    ${renderIdentityPerson({ name, avatarHtml, usernameHtml, connectionHtml })}
    <label class="participant-alias-label" for="${escapeText(inputId)}">כינוי</label>
    <div class="participant-alias-control">
      <input id="${escapeText(inputId)}" type="text" name="participantAlias" maxlength="32" autocomplete="off" enterkeyhint="done" data-action="participant-alias" data-event-id="${escapeText(eventId)}" data-participant-id="${escapeText(participantId)}" value="${escapeText(alias)}" placeholder="למשל, מהעבודה" aria-label="כינוי עבור ${escapeText(name)}" />
      <button class="secondary-button" type="button" data-action="save-participant-alias" data-event-id="${escapeText(eventId)}" data-participant-id="${escapeText(participantId)}">שמירה</button>
    </div>
  </div>`;
}
